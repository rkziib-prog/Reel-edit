# Splits the user's recording (input/phonecall/voice.mp3) into its 15 lines and re-spaces them with tense gaps.
# Line spans found with silencedetect (32 phrases matched to the script's 32 phrases, 16 Nov).
# Writes work/phonecall/voice_track.wav, work/phonecall/timeline.json and animations/phone-call/src/scenes/phone_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 4.47), (5.38, 9.05), (9.75, 12.78), (13.37, 15.57), (16.21, 19.17), (19.83, 21.92), (22.66, 24.89), (25.59, 27.50),
       (28.04, 30.15), (30.63, 34.29), (34.92, 37.01), (37.62, 40.64), (41.34, 47.72), (48.29, 50.29), (50.93, 53.79)]
GAP = [1.0, .9, .9, 1.3, 1.0, 1.1, 1.4, 1.8, .9, 1.2, 1.1, 1.6, 1.0, 1.5]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .5, 3.0, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/phonecall/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/phonecall/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/phonecall/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/phone-call/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/phone-call/src/scenes/phone_times.js").write_text(
    "// generated by edits/phone-call/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
