# Splits the user's recording (input/boat/voice.mp3) into its 15 lines and re-spaces them with tense gaps.
# Line spans found with silencedetect (35 phrases matched to the script's phrases, 17 Nov).
# Writes work/lastboat/voice_track.wav, work/lastboat/timeline.json and animations/last-boat/src/scenes/boat_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 5.19), (5.95, 9.47), (10.27, 13.78), (14.35, 17.80), (18.38, 21.18), (21.83, 25.18), (25.60, 28.65), (29.25, 32.26),
       (32.80, 36.42), (37.09, 41.12), (41.72, 45.11), (45.69, 49.15), (49.64, 56.58), (57.13, 60.54), (61.05, 64.47)]
GAP = [.7, .6, .6, .7, .6, .6, .8, .8, .9, 1.0, 1.1, .6, .9, 1.2]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .5, 3.0, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/boat/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/lastboat/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/lastboat/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/last-boat/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/last-boat/src/scenes/boat_times.js").write_text(
    "// generated by edits/last-boat/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
