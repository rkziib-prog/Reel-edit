# Splits the user's recording (input/coconut/voice.mp3) into its 15 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (28 phrases matched to the script's phrases, 23 Nov).
# Writes work/coconut/voice_track.wav, work/coconut/timeline.json and animations/coconut/src/scenes/coconut_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 4.39), (5.17, 7.97), (8.44, 12.61), (13.18, 17.13), (17.68, 21.19), (21.79, 26.78), (27.34, 30.46), (30.94, 36.38),
       (36.84, 40.57), (41.08, 43.96), (44.49, 49.44), (49.88, 54.36), (54.87, 58.97), (59.39, 64.25), (64.67, 68.10)]
GAP = [.5, .35, .35, .35, .35, .4, .35, .4, .35, .35, .45, .35, .45, .5]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .4, 2.2, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/coconut/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/coconut/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/coconut/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/coconut/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/coconut/src/scenes/coconut_times.js").write_text(
    "// generated by edits/coconut/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
