# Splits the user's recording (input/hairpin9/voice.mp3) into its 15 lines and re-spaces them with tense gaps.
# Line spans found with silencedetect (38 phrases matched to the script's phrases, 19 Nov).
# Writes work/hairpin9/voice_track.wav, work/hairpin9/timeline.json and animations/hairpin9/src/scenes/hairpin_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 5.39), (6.37, 10.84), (11.38, 14.62), (15.22, 19.12), (19.70, 22.96), (23.49, 25.78), (26.20, 28.26), (28.87, 30.96),
       (31.47, 35.11), (35.75, 38.78), (39.32, 43.71), (44.19, 47.30), (47.75, 53.81), (54.26, 58.92), (59.39, 65.95)]
GAP = [.8, .7, .8, .8, .7, .8, .9, 1.0, .7, 1.0, 1.0, .7, .9, 1.0]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .5, 3.0, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/hairpin9/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/hairpin9/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/hairpin9/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/hairpin9/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/hairpin9/src/scenes/hairpin_times.js").write_text(
    "// generated by edits/hairpin9/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
