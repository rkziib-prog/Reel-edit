# Splits the user's recording (input/upi/voice.mp3) into its 15 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (30 phrases matched to the script's phrases, 21 Nov).
# Writes work/upi/voice_track.wav, work/upi/timeline.json and animations/upi/src/scenes/upi_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 7.59), (8.11, 12.67), (13.21, 18.37), (18.86, 24.49), (24.94, 29.62), (30.05, 33.33), (33.81, 37.99), (38.42, 41.65),
       (42.08, 46.55), (47.00, 51.42), (51.89, 57.36), (57.80, 62.46), (62.91, 67.28), (67.73, 71.61), (72.04, 75.70)]
GAP = [.5, .35, .35, .35, .35, .4, .35, .4, .35, .35, .45, .35, .45, .5]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .4, 2.2, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/upi/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/upi/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/upi/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/upi/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/upi/src/scenes/upi_times.js").write_text(
    "// generated by edits/upi/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
