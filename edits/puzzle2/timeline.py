# Splits the user's recording (input/puzzle2/voice.mp3) into its 12 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (24 phrases matched to the script's phrases, 22 Nov).
# Writes work/puzzle2/voice_track.wav, work/puzzle2/timeline.json and animations/puzzle2/src/scenes/puzzle_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 2.91), (3.59, 7.79), (8.20, 10.98), (11.57, 15.82), (16.38, 20.87), (21.42, 26.27), (26.77, 29.50), (29.97, 34.49),
       (35.02, 36.46), (37.02, 39.62), (40.03, 42.67), (43.04, 46.48)]
GAP = [.5, .4, .45, .45, .45, .45, .45, .7, .4, 5.0, .4]   # after lines 1..11; 5 s think time after line 10
LEAD, TAIL, PAD = .4, 2.2, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/puzzle2/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/puzzle2/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/puzzle2/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/puzzle2/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/puzzle2/src/scenes/puzzle_times.js").write_text(
    "// generated by edits/puzzle2/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
