# Splits the user's recording (input/cooker/voice.mp3) into its 15 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (28 phrases matched to the script's phrases, 22 Nov).
# Writes work/cooker/voice_track.wav, work/cooker/timeline.json and animations/cooker/src/scenes/cooker_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 7.00), (7.51, 11.10), (11.58, 17.41), (17.85, 21.08), (21.58, 26.02), (26.44, 28.92), (29.33, 34.82), (35.30, 39.26),
       (39.75, 43.46), (43.91, 49.33), (49.81, 56.68), (57.10, 62.93), (63.33, 66.42), (66.87, 73.02), (73.46, 76.95)]
GAP = [.5, .35, .35, .35, .35, .4, .35, .4, .35, .35, .45, .35, .45, .5]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .4, 2.2, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/cooker/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/cooker/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/cooker/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/cooker/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/cooker/src/scenes/cooker_times.js").write_text(
    "// generated by edits/cooker/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
