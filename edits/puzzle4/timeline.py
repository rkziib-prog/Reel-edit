# Splits the user's recording (input/puzzle4/voice.mp3) into its 9 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (whisper + silences, 24 Nov).
# Writes work/puzzle4/voice_track.wav, work/puzzle4/timeline.json and animations/puzzle4/src/scenes/puzzle_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 3.28), (4.02, 7.59), (8.37, 10.44), (11.17, 14.06), (14.71, 17.41), (17.98, 22.84), (23.41, 25.53), (26.04, 30.24),
       (30.71, 34.04)]
GAP = [.5, .5, .5, .5, .6, .5, 5.0, .4]   # after lines 1..8; 5 s think time after line 7
LEAD, TAIL, PAD = .4, 2.2, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/puzzle4/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/puzzle4/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/puzzle4/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/puzzle4/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/puzzle4/src/scenes/puzzle_times.js").write_text(
    "// generated by edits/puzzle4/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
