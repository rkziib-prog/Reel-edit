# Splits the user's recording (input/puzzle3/voice.mp3) into its 14 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (whisper + silences, 24 Nov).
# Writes work/puzzle3/voice_track.wav, work/puzzle3/timeline.json and animations/puzzle3/src/scenes/puzzle_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 4.84), (5.32, 9.38), (10.19, 15.03), (15.61, 24.14), (24.82, 28.09), (28.68, 31.95), (32.53, 36.35), (36.90, 40.53),
       (41.07, 43.25), (43.55, 46.05), (46.68, 49.29), (49.96, 52.75), (52.99, 56.80), (57.10, 60.46)]
GAP = [.5, .45, .4, .5, .45, .45, .45, .45, .45, .6, .4, 5.0, .4]   # after lines 1..13; 5 s think time after line 12
LEAD, TAIL, PAD = .4, 2.2, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/puzzle3/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/puzzle3/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/puzzle3/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/puzzle3/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/puzzle3/src/scenes/puzzle_times.js").write_text(
    "// generated by edits/puzzle3/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
