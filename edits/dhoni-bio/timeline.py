# Splits the user's recording (input/dhoni/voice.mp3) into its 15 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (43 phrases matched to the script's phrases, 18 Nov).
# Writes work/dhoni/voice_track.wav, work/dhoni/timeline.json and animations/dhoni-bio/src/scenes/dhoni_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 4.37), (5.38, 10.93), (11.53, 16.69), (17.34, 20.77), (21.35, 24.31), (24.86, 31.93), (32.37, 38.25), (38.89, 44.83),
       (45.50, 49.71), (50.15, 54.77), (55.34, 61.15), (61.71, 67.07), (67.69, 75.23), (75.90, 83.69), (84.34, 90.59)]
GAP = [.6, .5, .5, .4, .5, .6, .5, .6, .4, .6, .5, .7, .6, .7]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .5, 3.0, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/dhoni/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/dhoni/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/dhoni/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/dhoni-bio/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/dhoni-bio/src/scenes/dhoni_times.js").write_text(
    "// generated by edits/dhoni-bio/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
