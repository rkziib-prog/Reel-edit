# Splits the user's recording (input/fastag/voice.mp3) into its 15 lines and re-spaces them with short gaps.
# Line spans found with silencedetect (34 phrases matched to the script's phrases, 20 Nov).
# Writes work/fastag/voice_track.wav, work/fastag/timeline.json and animations/fastag/src/scenes/fastag_times.js.
import json, subprocess, numpy as np, scipy.io.wavfile as wf, pathlib
SR = 48000
SEG = [(0.00, 5.12), (5.79, 10.49), (11.02, 14.71), (15.26, 19.97), (20.44, 24.87), (25.39, 30.95), (31.44, 36.13), (36.63, 42.68),
       (43.14, 47.77), (48.18, 52.40), (52.88, 55.83), (56.39, 60.09), (60.54, 65.21), (65.65, 70.83), (71.27, 74.79)]
GAP = [.5, .35, .35, .35, .35, .4, .35, .4, .35, .35, .45, .35, .45, .5]   # silence after lines 1..14 (s)
LEAD, TAIL, PAD = .4, 2.2, .06
raw = subprocess.run(["ffmpeg", "-v", "error", "-i", "/home/user/Reel-edit/input/fastag/voice.mp3", "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
a = np.frombuffer(raw, np.float32)
parts, starts, t = [], [], LEAD
for i, (s, e) in enumerate(SEG):
    s, e = max(0, s - PAD), min(len(a) / SR, e + PAD); clip = a[int(s * SR):int(e * SR)].copy()
    f = int(.02 * SR); clip[:f] *= np.linspace(0, 1, f); clip[-f:] *= np.linspace(1, 0, f)
    starts.append(round(t, 3)); parts.append((t, clip)); t += len(clip) / SR + (GAP[i] if i < len(GAP) else 0)
total = round(t + TAIL, 3)
out = np.zeros(int(total * SR) + SR, np.float32)
for st, c in parts: o = int(st * SR); out[o:o + len(c)] += c
wf.write("/home/user/Reel-edit/work/fastag/voice_track.wav", SR, out)
ends = [round(st + len(c) / SR, 3) for st, c in parts]
shots = [0.0] + [round(s - .25, 3) for s in starts[1:]]
json.dump(dict(starts=starts, ends=ends, shots=shots, total=total), open("/home/user/Reel-edit/work/fastag/timeline.json", "w"), indent=1)
pathlib.Path("/home/user/Reel-edit/animations/fastag/src/scenes").mkdir(parents=True, exist_ok=True)
pathlib.Path("/home/user/Reel-edit/animations/fastag/src/scenes/fastag_times.js").write_text(
    "// generated by edits/fastag/timeline.py: shot starts, line starts/ends (video time), total\n"
    f"const PT = {json.dumps(dict(shots=shots, starts=starts, ends=ends, total=total))};\n")
print("total", total); print("starts", starts); print("ends", ends)
