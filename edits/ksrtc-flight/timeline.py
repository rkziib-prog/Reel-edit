# Shot timing from the narration: each line gets its voice length + a gap; lines 6+7 share the lift-off shot.
# Writes animations/ksrtc-flight/src/scenes/ksrtc_times.js and work/ksrtc/timeline.json (voice/sub cue times).
import json, pathlib, scipy.io.wavfile as wf
V = pathlib.Path("/home/user/Reel-edit/work/ksrtc/voice")
LEAD, GAP, MIN = .15, .45, 2.0
d = []
for i in range(1, 16):
    sr, a = wf.read(V / f"line_{i:02d}.wav"); d.append(len(a) / sr)
dur = [max(MIN, x + GAP) for x in d]; dur[-1] += 1.6
starts = [round(sum(dur[:i]), 3) for i in range(15)]
total = round(sum(dur), 3)
# animation shots: line index (1-based) that each shot starts at; 6 and 7 merged
shot_lines = [1, 2, 3, 4, 5, 6, 8, 9, 10, 11, 12, 13, 14, 15]
shot_t = [starts[l - 1] for l in shot_lines]
js = f"// generated by edits/ksrtc-flight/timeline.py\nconst KT = {json.dumps(dict(shots=shot_t, total=total, bumpAt=round(starts[6]-starts[5], 3)))};\n"
pathlib.Path("/home/user/Reel-edit/animations/ksrtc-flight/src/scenes/ksrtc_times.js").write_text(js)
json.dump(dict(starts=starts, dur=dur, voice=d, total=total, lead=LEAD), open("/home/user/Reel-edit/work/ksrtc/timeline.json", "w"), indent=1)
print(js)
