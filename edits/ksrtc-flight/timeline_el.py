# Shot timing from the user's ElevenLabs recording (input/ksrtc/voice_akhil_el.mp3), kept with its own pacing.
# Line starts/ends were found with silencedetect + Whisper (15 Nov). Each shot starts 0.15 s before its line.
import json, pathlib
SEG = [(0.00, 4.57), (5.41, 11.12), (11.57, 16.23), (16.68, 20.46), (21.18, 24.39), (24.99, 26.42), (26.96, 28.63),
       (29.11, 31.28), (31.78, 35.64), (36.26, 38.98), (39.44, 42.51), (43.10, 46.05), (46.50, 51.80), (52.30, 55.86), (56.38, 58.36)]
starts = [0.0] + [round(a - .15, 3) for a, _ in SEG[1:]]
total = round(SEG[-1][1] + 1.6, 3)
shot_lines = [1, 2, 3, 4, 5, 6, 8, 9, 10, 11, 12, 13, 14, 15]
shots = [starts[l - 1] for l in shot_lines]
js = f"// generated by edits/ksrtc-flight/timeline_el.py\nconst KT = {json.dumps(dict(shots=shots, total=total, bumpAt=round(starts[6] - starts[5], 3)))};\n"
pathlib.Path("/home/user/Reel-edit/animations/ksrtc-flight/src/scenes/ksrtc_times.js").write_text(js)
json.dump(dict(starts=starts, total=total, shots=shots, voice_file="/home/user/Reel-edit/input/ksrtc/voice_akhil_el.mp3"),
          open("/home/user/Reel-edit/work/ksrtc/timeline.json", "w"), indent=1)
print(js)
